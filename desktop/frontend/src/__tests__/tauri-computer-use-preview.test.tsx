assert.equal(advanceComputerUsePreview(state, frame("tool_progress"))?.preview, null, "terminal owner rejects late images");
assert.equal(advanceComputerUsePreview(state, frame("turn_started"))?.ended, true, "duplicate starts cannot reopen a terminal turn");
state = advanceComputerUsePreview(state, frame("turn_started", "turn-2"));
assert.equal(advanceComputerUsePreview(state, frame("tool_progress"))?.preview, null, "previous turn cannot replace the current preview");
assert.equal(advanceComputerUsePreview(state, frame("turn_done"))?.turnId, "turn-2", "late terminal events cannot clear a newer owner");
