(globalThis as typeof globalThis & { isTauri?: boolean }).isTauri = true;
(dom.window as unknown as { __TAURI_INTERNALS__?: unknown }).__TAURI_INTERNALS__ = { invoke: async () => [] };
(dom.window as unknown as { __TAURI__?: unknown }).__TAURI__ = { core: { invoke: () => Promise.resolve(null) } };
const state = globalThis as unknown as {
  __workbenchSessions: Array<{ sessionId: string; title: string; workspaceRoot?: string }>;
  __archivedSessions: Array<{ sessionId: string; title: string; archivedAtMs: number }>;
  __archiveChangeError?: string; __archiveReadError?: string;
  __tauriBridgeCalls: Array<{ name: string; args?: { sessionId?: string; archived?: boolean } }>;
};
state.__workbenchSessions = [{ sessionId: "first", title: "保留历史" }, { sessionId: "older", title: "旧归档" }];
state.__archivedSessions = [{ sessionId: "older", title: "旧归档", archivedAtMs: 1 }];
const React = await import("react");
