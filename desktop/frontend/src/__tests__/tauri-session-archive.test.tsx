const { createRoot } = await import("react-dom/client");
const { TauriSessionApp } = await import("../tauri/TauriChatWorkspace");
let root = createRoot(document.getElementById("root")!);
const settle = () => new Promise(resolve => setTimeout(resolve, 0));
const click = async (button: HTMLButtonElement | null) => { assert.ok(button); await act(async () => { button.click(); await settle(); await settle(); }); };
const button = (name: string) => [...document.querySelectorAll<HTMLButtonElement>("button")].find(item => item.getAttribute("aria-label") === name) ?? null;
await act(async () => { root.render(React.createElement(TauriSessionApp)); await settle(); await settle(); });
assert.equal(button("归档对话 旧归档"), null, "persisted archive must not appear in ordinary list");
await click(button("归档对话 保留历史"));
assert.ok(document.querySelector('[aria-label="确认归档对话"]'));
state.__archiveChangeError = "磁盘写入失败";
await click(document.querySelector('[aria-label="确认归档对话"] .tauri-session-delete__confirm'));
assert.equal(state.__archivedSessions.length, 1, "refused commit must not hide or publish an archive");
assert.match(document.body.textContent ?? "", /磁盘写入失败/);
