await act(async () => { root.render(React.createElement(TauriSessionApp)); await settle(); await settle(); });
assert.equal(button("归档对话 保留历史"), null, "remount must reload persisted archive overlay");
await click([...document.querySelectorAll<HTMLButtonElement>("button")].find(item => item.classList.contains("tauri-archives-toggle")) ?? null);
