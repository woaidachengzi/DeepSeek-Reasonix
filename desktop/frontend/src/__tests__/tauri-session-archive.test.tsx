const restore = document.querySelector<HTMLButtonElement>('.tauri-archives-panel article button');
await click(restore);
assert.ok(state.__tauriBridgeCalls.some(call => call.name === "bridge_change_session_archive" && call.args?.archived === false));
assert.ok(state.__tauriBridgeCalls.some(call => call.name === "bridge_switch_session" && call.args?.sessionId === "older"), "restoration reopens original ID without stale archive guard");
assert.equal(document.querySelector('[role="dialog"][aria-label="已归档对话"]'), null);
